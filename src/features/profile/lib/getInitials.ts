import { isInvisibleCodePoint } from './visibleChars'

// Первый символ берём через Array.from, а не word[0]: индексация по строке работает по
// UTF-16 code units и режет суррогатную пару (эмодзи, редкие символы) пополам. Графемные
// кластеры (флаги, ZWJ-последовательности, комбинирующие знаки) не поддерживаются — это
// сознательное упрощение без Intl.Segmenter.
// toLocaleUpperCase, а не toUpperCase — имя может быть кириллическим, и локаль-зависимый
// вариант корректнее для нелатинских алфавитов. Результат может раскрыться в несколько
// символов ('ß' → 'SS'), поэтому берём именно первый символ уже после приведения регистра:
// одно слово всегда даёт ровно один символ инициала. Локаль передаём ФИКСИРОВАННОЙ
// (INITIALS_LOCALE), а не системной по умолчанию: с системной локалью то же самое имя
// рисовало бы разные инициалы на разных устройствах чисто из-за настройки ОС посетителя
// (турецкая/азербайджанская локаль превращает латинское 'i' в 'İ' — 'ivan' → 'İVAN' вместо
// 'IVAN'), никак не связанной с языком самого приложения. 'en' даёт тот же generic
// Unicode-регистр, что и без локали для кириллицы (кириллица не завязана на локаль так, как
// турецкое i/İ), так что корректность для нелатинских алфавитов не теряется.
const INITIALS_LOCALE = 'en'

// Первый ВИДИМЫЙ code point слова, а не буквально первый: normalizeProfileName принимает имя,
// у которого невидим только ведущий символ слова (само слово при этом не целиком невидимо), —
// без пропуска ведущих невидимых code points инициал сам оказался бы невидимым символом при
// непустом имени (пустой кружок вместо буквы). Если во всём слове нет ни одного видимого
// code point, слово не даёт инициала вовсе (не считается одним из «первых двух слов»).
const firstChar = (word: string): string => {
  const codePoints = Array.from(word.toLocaleUpperCase(INITIALS_LOCALE))
  return codePoints.find(codePoint => !isInvisibleCodePoint(codePoint)) ?? ''
}

export const getInitials = (name: string): string => {
  const initials = name.split(/\s+/).map(firstChar).filter(Boolean)

  return initials.slice(0, 2).join('')
}
